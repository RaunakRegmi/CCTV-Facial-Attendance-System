"""
Fine-tune YOLOv8n on the custom exam-contraband dataset.

Expected dataset layout (YOLO format, relative to backend/):

    yolo_contraband/
        images/train/*.jpg   labels/train/*.txt
        images/val/*.jpg     labels/val/*.txt

Label frames from capture_dataset.py (raw_frames/) in Label Studio with
these class names, export as YOLO to yolo_contraband/export.zip, then run
split_dataset.py to build the layout above:
    0 cell_phone   1 chit_paper   2 smartwatch   3 earbuds

Usage:
    python train_contraband.py                # 100 epochs, imgsz 640, batch 16
    python train_contraband.py --epochs 50    # quicker experiment

The best weights are copied to backend/contraband_yolov8n.pt, which
proctor_engine.py picks up automatically.
"""

import argparse
import shutil
from pathlib import Path

import torch
from ultralytics import YOLO

BASE_DIR = Path(__file__).resolve().parent
DATASET_DIR = BASE_DIR / "yolo_contraband"
DATA_YAML = DATASET_DIR / "data.yaml"
BASE_WEIGHTS = BASE_DIR / "yolov8n.pt"            # auto-downloaded by ultralytics if missing
OUTPUT_WEIGHTS = BASE_DIR / "contraband_yolov8n.pt"
RUNS_DIR = BASE_DIR / "runs"

# Order defines class IDs; must match CUSTOM_CLASSES in proctor_engine.py
CLASSES = ["cell_phone", "chit_paper", "smartwatch", "earbuds"]
IMAGE_EXTS = {".jpg", ".jpeg", ".png", ".bmp", ".webp"}


def write_data_yaml():
    names = "\n".join(f"  {i}: {name}" for i, name in enumerate(CLASSES))
    DATA_YAML.parent.mkdir(parents=True, exist_ok=True)
    DATA_YAML.write_text(
        f"# Generated by train_contraband.py\n"
        f"path: {DATASET_DIR.as_posix()}\n"
        f"train: images/train\n"
        f"val: images/val\n"
        f"\n"
        f"names:\n{names}\n"
    )
    print(f"[DATA] Wrote {DATA_YAML}")


def check_dataset():
    """Fails early with a clear message instead of a deep ultralytics traceback."""
    for split in ("train", "val"):
        img_dir = DATASET_DIR / "images" / split
        lbl_dir = DATASET_DIR / "labels" / split
        images = [p for p in img_dir.glob("*") if p.suffix.lower() in IMAGE_EXTS] if img_dir.exists() else []
        labels = list(lbl_dir.glob("*.txt")) if lbl_dir.exists() else []
        if not images:
            raise SystemExit(
                f"No images in {img_dir}.\n"
                f"Label frames from yolo_contraband/raw_frames in Label Studio, export as YOLO to "
                f"yolo_contraband/export.zip, then run: python split_dataset.py"
            )
        if not labels:
            raise SystemExit(f"No label .txt files in {lbl_dir}.")
        print(f"[DATA] {split}: {len(images)} images, {len(labels)} label files")


def pick_device():
    if torch.backends.mps.is_available():
        return "mps"
    print("[DEVICE] MPS unavailable, falling back to CPU (training will be slow)")
    return "cpu"


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--epochs", type=int, default=100)
    parser.add_argument("--imgsz", type=int, default=640)
    parser.add_argument("--batch", type=int, default=16)
    args = parser.parse_args()

    write_data_yaml()
    check_dataset()
    device = pick_device()
    print(f"[TRAIN] yolov8n | epochs={args.epochs} imgsz={args.imgsz} batch={args.batch} device={device}")

    model = YOLO(str(BASE_WEIGHTS))
    model.train(
        data=str(DATA_YAML),
        epochs=args.epochs,
        imgsz=args.imgsz,
        batch=args.batch,
        device=device,
        project=str(RUNS_DIR),
        name="contraband",
        exist_ok=False,  # new run dir each time (contraband, contraband2, ...)
    )

    best = Path(model.trainer.best)
    if not best.exists():
        raise SystemExit(f"Training finished but best weights were not found at {best}")
    shutil.copy2(best, OUTPUT_WEIGHTS)
    print(f"[DONE] Best weights copied to {OUTPUT_WEIGHTS}")
    print("       proctor_engine.py will now use the custom 4-class model automatically.")


if __name__ == "__main__":
    main()
